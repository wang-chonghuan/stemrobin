// The landing page: a white page whose one dark surface is the knowledge
// galaxy, so the map reads as the product and the words read as the argument.
//
// It sits outside the `_app` layout, so the catalog rail does not appear here.
// "Start learning" hands over to /learn, which is inside that layout — that is
// where the rail, the deck numbers and the lessons live. Class prefix `lw-`.

