function LandingLight() {
  const { locale, lessonIds } = Route.useLoaderData()
  const router = useRouter()
  const t = COPY[locale]
  const [menuOpen, setMenuOpen] = useState(false)
  const [navOpen, setNavOpen] = useState(false)
  const [query, setQuery] = useState('')
  const [openBook, setOpenBook] = useState<string | null>(null)
  const [mapReady, setMapReady] = useState(false)
  const navRef = useRef<HTMLElement>(null)
  const galaxyRef = useRef<GalaxyApi | null>(null)

  const outline = getTextbookOutline(lessonIds, locale)

  useEffect(() => {
    if (!menuOpen) return
    const onDown = (e: MouseEvent) => {
      if (navRef.current && !navRef.current.contains(e.target as Node)) setMenuOpen(false)
    }
    const onKey = (e: KeyboardEvent) => e.key === 'Escape' && setMenuOpen(false)
    document.addEventListener('mousedown', onDown)
    document.addEventListener('keydown', onKey)
    return () => {
      document.removeEventListener('mousedown', onDown)
      document.removeEventListener('keydown', onKey)
    }
  }, [menuOpen])

  useEffect(() => {
    if (!navOpen) return
    const onKey = (e: KeyboardEvent) => e.key === 'Escape' && setNavOpen(false)
    document.addEventListener('keydown', onKey)
    return () => document.removeEventListener('keydown', onKey)
  }, [navOpen])

  async function switchLocale() {
    await setLocale({ data: locale === 'zh' ? 'en' : 'zh' })
    await router.invalidate()
  }

  const q = query.trim().toLowerCase()
  const matches =
    q && galaxyRef.current
      ? galaxyRef.current.stars
          .map((star, index) => ({ star, index }))
          .filter(
            ({ star }) =>
              star.title.toLowerCase().includes(q) ||
              (star.titleEn ?? '').toLowerCase().includes(q),
          )
          .slice(0, 8)
      : []

  // Volumes on the left, the chosen volume's chapters and numbered sections on
  // the right. Unnumbered matter — closing problem sets, appendices — belongs
  // in the lesson, not in a nav panel.
  const allBooks = outline.flatMap((d) => d.books)
  const activeBook = allBooks.find((b) => b.book === openBook) ?? allBooks[0]
  const activeContents = activeBook?.contents ?? []

  const sectionRow = (l: OutlineLesson) =>
    l.ready ? (
      <Link
        key={l.id}
        to="/lesson/$id"
        params={{ id: l.id }}
        className="lw-map-sec"
        onClick={() => {
          setMenuOpen(false)
          setNavOpen(false)
        }}
      >
        <b>{l.number}</b>
        <span>{l.title}</span>
      </Link>
    ) : (
      <div key={l.id} className="lw-map-sec off">
        <b>{l.number}</b>
        <span>{l.title}</span>
      </div>
    )

  const curriculumMap = (
    <div className="lw-map">
      <div className="lw-map-books">
        {outline.map((d) => (
          <div key={d.discipline}>
            <div className={'lw-map-disc ' + d.discipline}>{d.label}</div>
            {d.books.map((b) => {
              const ready = bookLessons(b).filter((l) => l.ready).length
              return (
                <button
                  key={b.book}
                  type="button"
                  className={'lw-map-book' + (activeBook?.book === b.book ? ' active' : '')}
                  onMouseEnter={() => setOpenBook(b.book)}
                  onFocus={() => setOpenBook(b.book)}
                  onClick={() => setOpenBook(b.book)}
                >
                  <span>{b.title}</span>
                  <small>{ready ? t.ready(ready) : t.comingSoon}</small>
                </button>
              )
            })}
          </div>
        ))}
      </div>
      <div className="lw-map-detail">
        {activeContents
          .filter((n): n is Extract<OutlineNode, { kind: 'chapter' }> => n.kind === 'chapter')
          .map((ch) => ({ ch, secs: ch.lessons.filter((l) => /^\d+\.\d+$/.test(l.number)) }))
          .filter(({ secs }) => secs.length > 0)
          .map(({ ch, secs }) => (
            <div key={ch.id} className="lw-map-chapter">
              <h4>{ch.label}</h4>
              <div className="lw-map-secs">{secs.map(sectionRow)}</div>
            </div>
          ))}
      </div>
    </div>
  )

  return (
    <div className="lw-page">
      <button
        type="button"
        className={'lw-scrim' + (navOpen ? ' show' : '')}
        aria-label={t.closeMenu}
        tabIndex={navOpen ? 0 : -1}
        onClick={() => setNavOpen(false)}
      />
      <aside className={'lw-drawer' + (navOpen ? ' open' : '')} aria-hidden={!navOpen}>
        <div className="lw-drawer-books">{curriculumMap}</div>
        <div className="lw-drawer-ctas">
          <button type="button" className="lw-btn ghost" onClick={switchLocale}>
            {t.langButton}
          </button>
          <Link to="/login" className="lw-btn ghost" onClick={() => setNavOpen(false)}>
            {t.signIn}
          </Link>
          <Link to="/learn" className="lw-btn solid" onClick={() => setNavOpen(false)}>
            {t.startFree}
          </Link>
        </div>
      </aside>

      <header className="lw-nav" ref={navRef}>
        <div className="lw-nav-inner">
          <Link to="/" className="lw-brand">
            <img src="/logo-mark.png" alt="" width={34} height={34} />
            <span className="lw-brand-name">
              Lemma<em>Deck</em>
              <small>{t.brandSub}</small>
            </span>
          </Link>
          <nav className="lw-nav-links">
            <button
              type="button"
              className={'lw-nav-link dropdown' + (menuOpen ? ' open' : '')}
              aria-expanded={menuOpen}
              aria-haspopup="menu"
              onClick={() => setMenuOpen((v) => !v)}
            >
              {t.navMap}
            </button>
          </nav>
          <div className="lw-nav-actions">
            <button type="button" className="lw-lang" onClick={switchLocale}>
              {t.langButton}
            </button>
            <Link to="/login" className="lw-btn ghost">
              {t.signIn}
            </Link>
          </div>
          <button
            type="button"
            className="lw-burger"
            aria-label={navOpen ? t.closeMenu : t.openMenu}
            aria-expanded={navOpen}
            onClick={() => setNavOpen((v) => !v)}
          >
            {navOpen ? <X size={20} /> : <Menu size={20} />}
          </button>
        </div>
        {menuOpen && (
          <div className="lw-mega" role="menu">
            {curriculumMap}
          </div>
        )}
      </header>

      <main className="lw-content">
        {/* The argument on the left, the product on the right. The galaxy keeps
            its dark skin — the one dark surface on a white page. */}
        <section className="lw-hero">
          <div className="lw-hero-copy">
            <h1>{t.h1}</h1>
            <p className="lw-lead">{t.lead}</p>
            <p className="lw-body">{t.body}</p>
            <p className="lw-outcome">{t.outcome}</p>
            <div className="lw-ctas">
              <Link to="/learn" className="lw-btn solid lg">
                {t.startFree}
              </Link>
            </div>
          </div>

          <div className="lw-hero-galaxy">
            <div className="lw-galaxy-frame">
              <KnowledgeGalaxy
                locale={locale}
                theme="dark"
                bare
                edgeBoost={3.2}
                apiRef={galaxyRef}
                onReady={() => setMapReady(true)}
              />
              {!mapReady && (
                <div className="lw-galaxy-skeleton" aria-hidden>
                  <span />
                </div>
              )}
              <div className={'lw-galaxy-zoom' + (mapReady ? '' : ' hidden')}>
                <button type="button" aria-label={t.zoomIn} onClick={() => galaxyRef.current?.zoomBy(0.78)}>
                  <Plus size={15} />
                </button>
                <button type="button" aria-label={t.zoomOut} onClick={() => galaxyRef.current?.zoomBy(1.28)}>
                  <Minus size={15} />
                </button>
              </div>
            </div>
            <div className="lw-hero-galaxy-foot">
              <p className="lw-hero-galaxy-hint">{t.mapHint}</p>
              <div className="lw-search">
                <Search size={14} aria-hidden />
                <input
                  type="search"
                  value={query}
                  placeholder={t.searchPlaceholder}
                  onChange={(e) => setQuery(e.target.value)}
                  aria-label={t.searchPlaceholder}
                />
                {matches.length > 0 && (
                  <div className="lw-search-pop" role="listbox">
                    {matches.map(({ star, index }) => (
                      <button
                        key={star.id}
                        type="button"
                        role="option"
                        aria-selected="false"
                        onClick={() => {
                          galaxyRef.current?.focusStar(index)
                          setQuery('')
                        }}
                      >
                        <span>{locale === 'zh' ? star.title : (star.titleEn ?? star.title)}</span>
                        <i className={star.discipline} />
                      </button>
                    ))}
                  </div>
                )}
              </div>
            </div>
          </div>
        </section>

        <blockquote className="lw-quote">
          <p>{t.quote}</p>
          <cite>
            {t.quoteBy}
            <span className="lw-quote-title">{t.quoteByTitle}</span>
          </cite>
        </blockquote>

        <section className="lw-points">
          <h2>{t.pointsTitle}</h2>
          <ol>
            {t.points.map((p, i) => (
              <li key={p}>
                <span className="lw-point-n">{String(i + 1).padStart(2, '0')}</span>
                <p>{p}</p>
              </li>
            ))}
          </ol>
        </section>

        <section className="lw-cta">
          <h2>{t.ctaTitle}</h2>
          <div className="lw-ctas">
            <Link to="/learn" className="lw-btn solid lg">
              {t.startFree}
            </Link>
            <button type="button" className="lw-btn ghost lg" onClick={() => setMenuOpen(true)}>
              {t.ctaSecondary}
            </button>
          </div>
        </section>
      </main>
    </div>
  )
}
